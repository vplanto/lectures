def generate_complex_degenerate_matrix(n=10, rank=5):
    """Автоматична генерація виродженої матриці 10x10 природним шляхом"""
    A = np.random.rand(n, rank)
    B = np.random.rand(rank, n)
    matrix = np.dot(A, B)
    return matrix / matrix.sum(axis=1)[:, None]

# 1. Ініціалізація системи
N_STATES = 10
CHANNEL_MATRIX = generate_complex_degenerate_matrix(N_STATES, rank=8)

class AdvancedInfoGenerator:
    def __init__(self, matrix, n_states):
        self.matrix = matrix
        self.n_states = n_states

    def generate(self, size=100000, is_structured=True):
        X, Y = [], []
        # СТРАТЕГІЯ: Система "пар" (X0->X5, X1->X6...)
        # Це набагато складніша семантика для розпізнавання
        curr_x = np.random.randint(5)

        for _ in range(size):
            if is_structured:
                # Якщо зараз стан від 0 до 4, наступним МАЄ бути відповідний стан від 5 до 9
                if curr_x < 5:
                    next_x = curr_x + 5
                else:
                    next_x = np.random.randint(5) # Потім новий випадковий запит
            else:
                next_x = np.random.choice(self.n_states)

            y_val = np.random.choice(self.n_states, p=self.matrix[next_x])
            X.append(next_x)
            Y.append(float(y_val))
            curr_x = next_x

        return np.array(X), np.array(Y).reshape(-1, 1)

