# 1. Оновлена архітектура моделі
class SemanticDecoder(nn.Module):
    def __init__(self, n_states, embed_dim=8):
        super().__init__()
        self.embeddings = nn.Embedding(n_states, embed_dim)
        # Додаємо потужності: 2 шари GRU та Dropout для стабільності
        self.rnn = nn.GRU(embed_dim, 64, num_layers=2, batch_first=True, dropout=0.1)
        self.fc = nn.Linear(64, n_states)

    def forward(self, x):
        x = self.embeddings(x)
        out, _ = self.rnn(x)
        return self.fc(out[:, -1, :])

def calculate_conditional_entropy(y_pred_probs):
    epsilon = 1e-12
    entropy = -np.mean(np.sum(y_pred_probs * np.log2(y_pred_probs + epsilon), axis=1))
    return entropy

def run_scientific_experiment_final(n_runs=5):
    sem_accs, class_accs, sem_entropies = [], [], []
    S_LEN = 20

    # 1. Готуємо дані (вони поки на CPU)
    train_in_f, train_out_f = to_sequences(Y_train, X_train, seq_len=S_LEN)
    test_in_f, test_out_f = to_sequences(Y_test, X_test, seq_len=S_LEN)

    # Створюємо DataLoader
    train_loader = DataLoader(TensorDataset(train_in_f, train_out_f), batch_size=2048, shuffle=True)

    temp_preds_len = len(test_out_f)
    y_true_local = test_out_f.numpy()
    y_obs_classical = Y_test[S_LEN-1 : S_LEN-1 + temp_preds_len].flatten()

    print(f"Починаємо фінальну серію (Rank=8, Batching active)...")

    for run in range(n_runs):
        run_model = SemanticDecoder(N_STATES, embed_dim=8).to(device)
        run_opt = optim.Adam(run_model.parameters(), lr=0.001)

        run_model.train()
        for epoch in range(150): # 150 епох
            for b_in, b_out in train_loader:
                # ПЕРЕНОСИМО БАТЧ НА GPU
                b_in, b_out = b_in.to(device), b_out.to(device)
                run_opt.zero_grad()
                loss = nn.CrossEntropyLoss()(run_model(b_in), b_out)
                loss.backward()
                run_opt.step()

        run_model.eval()
        with torch.no_grad():
            test_outputs = []
            # Тестуємо теж батчами, щоб не було OutOfMemory
            for i in range(0, len(test_in_f), 2048):
                batch_test = test_in_f[i:i+2048].to(device) # ПЕРЕНОСИМО НА GPU
                test_outputs.append(run_model(batch_test))

            outputs = torch.cat(test_outputs)
            probs = torch.softmax(outputs, dim=1).cpu().numpy()
            preds = np.argmax(probs, axis=1)

            acc = accuracy_score(y_true_local, preds)
            ent = calculate_conditional_entropy(probs)
            sem_accs.append(acc)
            sem_entropies.append(ent)

            c_preds = [np.argmax(CHANNEL_MATRIX[:, int(y)]) for y in y_obs_classical]
            class_accs.append(accuracy_score(y_true_local, c_preds))

        print(f"Запуск {run+1}: Accuracy={acc:.4f}, Entropy={ent:.4f}")

    return sem_accs, class_accs, sem_entropies, run_model


# ВИКОНАННЯ
